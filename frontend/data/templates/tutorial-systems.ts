import { Node, Edge } from 'reactflow';

/**
 * Templates for the systems that had a system design tutorial but no diagram: WhatsApp,
 * Twitter, Airbnb, Discord, Zoom, Spotify, LinkedIn, Figma, GitHub and a rate limiter.
 * Each contains every component its tutorial teaches (`data/tutorials/<id>-architecture.ts`)
 * plus the parts a complete design needs, so the template page and the tutorial agree.
 * Positions are rough columns; `loadTemplate` and the template images re-lay them out.
 */

const C = { client: '#64748b', edge: '#0f766e', compute: '#0d9488', data: '#334155', async: '#b45309', observe: '#475569' } as const;
type Layer = keyof typeof C;
const n = (id: string, label: string, subtitle: string, layer: Layer, icon: string, x: number, y: number): Node => ({
  id, type: 'systemNode', position: { x, y },
  data: { label, subtitle, layer, category: layer, color: C[layer], icon, nodeWidth: 182, nodeHeight: 82 },
});
const e = (id: string, source: string, target: string, label: string, kind: 'sync' | 'async' | 'event' | 'stream' | 'dep' = 'sync'): Edge => ({
  id, source, target, type: 'simpleFloating', animated: kind !== 'sync', label,
  data: { label, edgeType: kind, connectionType: kind, pathType: 'Smoothstep' }, style: { strokeWidth: 1.5 },
});

